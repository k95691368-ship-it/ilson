// 지금 되돌릴 것이 있는가.
//
// 시연 신청서가 하나도 없으면 되돌린다는 말이 뜻이 없다. 그때는 "심기"가
// 맞는 말이다.
export function resetLabel(demoCount) {
  const n = Number(demoCount)
  if (!Number.isFinite(n) || n <= 0) return '시연 신청서 심기'
  return '시연 신청서를 처음 상태로'
}
