// 지금 빈 상태인가.
//
// 숫자 하나로 가른다. 0이면 초대문이 아니라 채우는 자리를 보여줘야 한다.
export function isEmptySite(counts) {
  const raw = counts?.total
  // 아직 못 읽었으면 빈 것으로 치지 않는다. 불러오는 중에 "비어 있습니다"가
  // 번쩍했다가 사라지면 잘못 만든 화면처럼 보인다.
  //
  // Number(null) 은 0이다. 이 저장소에서 같은 함정에 네 번 빠졌다 — 아무것도
  // 안 물어봤는데 "부서가 다르게 말했습니다"가 뜨고, 인원을 안 보냈는데
  // 1명으로 굳고, 여기서는 아직 못 읽은 것을 "비어 있습니다"로 말할 뻔했다.
  // 숫자로 바꾸기 **전에** 없는 값부터 걸러 낸다.
  if (raw == null || raw === '') return false
  const n = Number(raw)
  if (!Number.isFinite(n)) return false
  return n === 0
}
