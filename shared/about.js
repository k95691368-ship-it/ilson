// 화면이 숫자를 지어내지 않게, 셀 수 있는 것만 서버에서 받는다.
export function techFacts(counts) {
  const c = counts ?? {}
  return [
    { k: '테스트', v: c.tests != null ? `${c.tests.toLocaleString()}개` : null },
    { k: 'API 라우트', v: c.routes != null ? `${c.routes}개` : null },
    { k: '화면', v: c.pages != null ? `${c.pages}개` : null },
    { k: 'DB 테이블', v: c.tables != null ? `${c.tables}개` : null },
    { k: '공용 모듈', v: c.shared != null ? `${c.shared}개 (브라우저·Worker 공유)` : null },
  ].filter((x) => x.v)
}
