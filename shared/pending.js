export function pendingText(code) {
  return PENDING_TEXT[code] ?? null
}

// 급한 차례.
//
// 넘겨받은 것을 못 쓰고 있는 것이 가장 급하다 — 그건 부서가 지금 일을
// 못 하고 있다는 뜻이다. 그다음이 판정을 막고 있는 것, 그다음이 기록을
// 정확하게 만드는 것.
const ORDER = ['accept', 'hold', 'signoff', 'beta', 'outcome']

export function sortPending(list) {
  return (list ?? [])
    .slice()
    .sort((a, b) => {
      const d = ORDER.indexOf(a.code) - ORDER.indexOf(b.code)
      if (d !== 0) return d
      // 같은 종류면 오래 기다린 것부터.
      return String(a.since ?? '').localeCompare(String(b.since ?? ''))
    })
}

// 부서에게 뭐라고 말할 것인가.
export function pendingHeadline(dept, list) {
  const n = (list ?? []).length
  if (n === 0) return `${dept}에서 지금 답해 주실 것은 없습니다`
  return `${dept}에서 답해 주셔야 진행되는 것 ${n}가지`
}

export function pendingWhy(list) {
  if ((list ?? []).length === 0) {
    return '새로 생기면 여기에 뜹니다. 이 주소를 저장해 두시면 신청서를 하나씩 열어 보지 않으셔도 됩니다.'
  }
  // 재촉하지 않는다. 왜 막혀 있는지만 말한다 — 이것이 있으면 저희 쪽에서는
  // 더 못 나간다는 사실 자체가 재촉보다 강하다.
  return '이게 있으면 저희 쪽에서는 더 못 나갑니다. 하나씩 눌러 보시면 그 자리에서 바로 답하실 수 있습니다.'
}
