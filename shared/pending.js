// 이 부서가 답해 주셔야 할 것.
//
// 부서 화면(/dept/:dept)은 통째로 **담당자 시점**이다. 맨 위 제목부터가
// "내가 이 부서에 못 준 것"이다. 그건 맞는 설계다 — 부서와 마주 앉기 전에
// 봐야 할 것은 저쪽이 안 해 준 것이 아니라 내가 못 준 것이니까.
//
// 그런데 그 반대쪽이 아무 데도 없다. **부서 사람이 "우리가 답해야 할 것"을
// 보려면 신청서를 하나씩 열어 봐야 한다.** 세 건을 낸 부서라면 세 번
// 열어서 각 화면 중간쯤에 있는 카드를 찾아야 안다.
//
// 정직 화면은 이제 "부서에 N번 부탁드렸고 M번 답을 받았습니다"라고 말한다.
// 그 미응답 M-N건이 **어느 부서 몫인지**는 담당자만 안다. 정작 답해야 할
// 사람은 자기 몫이 몇 건인지 모른다. 부탁해 놓고 목록은 안 주는 셈이다.
//
// 그래서 같은 화면에 두되 **시점을 섞지 않는다.** 담당자 몫과 부서 몫을
// 한 덩어리로 만들면 둘 다 자기 것이 아닌 줄 알고 안 읽는다.

// 부탁 다섯 가지를 부서 눈높이의 한 줄로. shared/response.js 의 ASKS 와
// 짝이다 — 저쪽은 담당자가 세는 말, 이쪽은 부서에게 하는 말이다.
