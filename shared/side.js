// 이 기록은 누가 남긴 것인가 — 담당자인가, 부서인가.
//
// 결정 기록 화면(/log)은 이 사이트가 파는 것 그 자체다. "내가 무슨 일을
// 했는가"의 증거이기 때문이다. 그런데 지금 56건이 전부 `actor: 'human'`
// 하나로 뭉뚱그려져 있다. **담당자가 판단한 것과 부서가 응답한 것을 가를
// 수가 없다.**
//
// 이게 왜 문제냐면, 이 사이트가 여러 화면에서 되풀이하는 주장이 이것이기
// 때문이다 —
//   "넘겼다고 받은 것이 아니다"
//   "만든 사람만 아는 성과는 성과가 아니다"
//   "부서가 아니라고 하면 아닌 것이다"
//
// 그 주장을 뒷받침하는 가장 강한 숫자는 **부서가 실제로 몇 번 응답했는가**인데,
// 지금은 그걸 셀 수가 없다. 자기 주장의 증거를 자기가 안 세고 있었다.
//
// 기록의 종류(link_kind)로 가른다. 사람 이름으로 가르지 않는다 — 담당자가
// 부서 사람 이름으로 대신 눌러 준 것이 실제로 있고, 그건 부서 응답이
// 아니기 때문이다.

// 부서 쪽 사람이 직접 눌러야만 생기는 기록.
export const DEPT_KINDS = new Set([
  '수령확인', // 넘겨받은 도구를 받았다고 확인
  '수령거절', // 못 쓰겠다고 함
  '성과확인', // 적어 드린 숫자가 체감과 맞는지
  '기준서명', // 합격 기준 확인
  '기준이의', // 그 기준은 아니라고 함
  '보류해제요청', // 보류 조건이 풀렸다고 알림
  '보류해제취소', // 그 알림을 거둠
  '사용법모름', // 사용법서에서 모르겠는 곳을 짚음
  '같은건손듦', // 다른 부서가 같은 병목에 손듦
  '같은건아님', // 그 손을 내림
  '재신청', // 반려된 것을 고쳐서 다시 냄
  '답변', // 담당자가 되물은 것에 부서가 답함
  '코드확인', // 부서가 상품코드를 알려줌
  '신고', // 넘겨받은 도구가 이상하다고 신고
  // 아래 둘이 빠져 있었다. 부서가 한 일인데 기본값이 '담당자'라 조용히
  // 담당자 쪽으로 세어졌다. 그러면 "부서가 직접 누른 것 N건"이 실제보다
  // 적게 나오고, 이 화면이 하려는 말(혼자 만든 것이 아니다)이 약해진다.
  '부서질문', // 부서가 먼저 물어봄
  '시험판의견', // 시험판을 써 보고 걸리는 것을 적음
])

// 담당자가 부서를 대신해 눌러 준 것.
//
// 지우지 않는다 — 전화로 확인받고 대신 눌러야 할 때가 실제로 있다. 다만
// **부서 응답으로 세지 않는다.** 그러면 "부서가 확인해 줘야 성과다"가
// 자기 입으로 한 말이 된다.
export const PROXY_KINDS = new Set(['수령대리확인', '성과대리확인'])

export const SIDES = [
  { key: 'ax', label: '담당자가 한 것', hint: '판정·협의·제작·배포 — 내가 정한 것들' },
  { key: 'dept', label: '부서가 한 것', hint: '확인·서명·이의·신고 — 부서가 직접 누른 것' },
  { key: 'proxy', label: '담당자가 대신 누른 것', hint: '전화로 듣고 대신 눌러 둔 것. 부서 응답으로 세지 않는다' },
]

export function sideOf(kind) {
  const k = String(kind ?? '').trim()
  if (PROXY_KINDS.has(k)) return 'proxy'
  if (DEPT_KINDS.has(k)) return 'dept'
  // 종류가 없는 기록은 담당자가 단계를 진행하며 남긴 것이다 — 판정, 협의안
  // 확정, 제작, 배포처럼 애초에 담당자만 할 수 있는 일들.
  return 'ax'
}

export function sideLabel(key) {
  return SIDES.find((s) => s.key === key)?.label ?? key
}

// 부서가 얼마나 응답했는가.
//
// 이 사이트의 주장을 뒷받침하는 숫자다. 대리로 누른 것은 따로 센다 —
// 섞어 세면 자기 주장을 자기가 무너뜨린다.
export function sideTally(rows) {
  const t = { ax: 0, dept: 0, proxy: 0, total: 0 }
  for (const r of rows ?? []) {
    const s = sideOf(r?.link_kind)
    t[s] += 1
    t.total += 1
  }
  return t
}

export function sideLine(t) {
  if (!t || t.total === 0) return null
  if (t.dept === 0 && t.proxy === 0) {
    // 부서 응답이 하나도 없으면 그것부터 말해야 한다. 숨기면 이 화면이
    // "부서가 참여했다"는 인상만 주고 근거는 안 준다.
    return `${t.total}건 전부 담당자가 남긴 것입니다. 부서가 직접 누른 것은 아직 없습니다.`
  }
  const proxy = t.proxy > 0 ? ` 담당자가 대신 눌러 둔 것은 ${t.proxy}건인데, 이건 부서 응답으로 세지 않습니다.` : ''
  return `${t.total}건 중 ${t.dept}건은 부서가 직접 누른 것입니다.${proxy}`
}
