// 무엇이 얼마나 급한가 — 사이트 한 벌.
//
// 이 사다리가 shared/todo.js 안에만 있었다. 그런데 접기를 넣으면서 화면마다
// "이건 접어도 되나"를 각자 판단하게 됐고, 그러면 어느 화면에서는 접히고
// 어느 화면에서는 안 접힌다. 같은 성격의 것이 화면에 따라 다르게 다뤄지는
// 것이 이 저장소가 되풀이 잡아 온 바로 그 모양이다.
//
// 그래서 사다리를 밖으로 꺼낸다. todo.js 도 여기서 가져다 쓴다.
//
//   금액 3 — 숫자가 틀린다. 그대로 두면 틀린 값이 위로 보고된다.
//   대기 2 — 사람이 기다린다. 늦는 것보다 아무 말이 없는 것이 나쁘다.
//   정리 1 — 나중에 문제가 될 것. 오늘 아침에 눌러야 하는 것은 아니다.
export const URGENCY = { 금액: 3, 대기: 2, 정리: 1 }

// 이 무게부터는 접지 않는다.
//
// 접는 것은 "지금 안 봐도 된다"는 뜻이다. 금액이 틀린다는 신고에 그 말을
// 하면 안 된다. 되돌릴 수 없는 길의 경고도 마찬가지다.
export const NEVER_FOLD = 3

// 이 목록에 든 것은 무게와 상관없이 접지 않는다. 접기를 넣는 사람이
// 매번 판단하지 않게, 이름으로 못 박아 둔다.
export const NEVER_FOLD_KINDS = new Set([
  '금액', // 숫자가 틀린다는 신고
  '막음', // 지금 다음 단계로 못 가게 막고 있는 것
  '되돌릴수없음', // 누르면 되돌릴 수 없는 것의 경고
  '못불러옴', // 못 센 것을 안 센 것처럼 보이게 하면 안 된다
])

export function rankOf(kind) {
  if (NEVER_FOLD_KINDS.has(kind)) return NEVER_FOLD
  return URGENCY[kind] ?? 1
}

export function canFold(kind) {
  return rankOf(kind) < NEVER_FOLD
}
