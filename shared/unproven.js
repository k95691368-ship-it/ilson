// "증명하지 못한 것" 다섯 가지.
//
// 이건 데이터에서 뽑을 수 없는 종류의 한계라 손으로 적는다. 그런데 손으로
// 적었더니 **데이터가 바뀌어도 문장이 그대로 남았다.**
//
// 실제로 그랬다. 화면은 "여덟 단계를 끝까지 간 것은 한 건뿐입니다"라고
// 단언하고 있었는데, 그런 신청서는 한 건도 없었다. 넘긴 도구도, 재 둔
// 기준선도 0이었다. 하필 이 화면이 자기 소개문에 "데이터에서 자동으로
// 만들어지므로 잘 보이려고 손댈 수 없습니다"라고 적어 둔 자리다. 정직을
// 파는 화면이 손으로 적은 거짓을 달고 있으면 나머지 숫자도 못 믿는다.
//
// 그래서 **숫자에 걸리는 세 가지는 숫자를 받아서 문장을 고른다.**
//
// 없을 때 항목을 빼지 않는다. "끝까지 간 것이 없습니다"는 "한 건뿐입니다"
// 보다 **더 큰 한계**다. 빼 버리면 한계를 숨기는 것이 된다.

// 0을 지어내지 않는다. `Number(null)`은 0이라 그냥 넘기면 "안 물어본 것"이
// "0이라고 답한 것"으로 바뀐다 — 이 저장소에서 다섯 번 걸린 자리다.
function count(v) {
  if (v == null || v === '') return 0
  const n = Number(v)
  return Number.isFinite(n) ? n : 0
}

export function unprovenList(counts) {
  const c = counts ?? {}
  const finished = count(c.finished) // 여덟 단계를 끝까지 간 신청서
  const baselines = count(c.baselines) // 봉인한 기준선
  const samples = count(c.baselineSamples) // 기준선을 재려고 사람이 직접 해 본 횟수
  const runs = count(c.runs) // 넘긴 뒤 도구가 실제로 돌아간 횟수

  return [
    baselines === 0
      ? {
          key: 'sample_size',
          title: '기준선을 아직 한 번도 재지 않았습니다',
          body:
            '자동화 전에 사람이 그 일을 직접 해 보고 시간을 재 두는 것이 절감액의 바닥이 됩니다. 지금은 그 값이 하나도 없습니다.',
          instead:
            '그래서 지금은 얼마나 줄었는지를 말하지 않습니다. 재지 않은 상태에서 낸 절감액은 추정이 아니라 지어낸 것입니다. 재는 자리는 만들어 뒀고, 재기 전에는 성과 화면이 「산정불가」로 남습니다.',
        }
      : {
          key: 'sample_size',
          title: `기준선을 ${samples}번밖에 안 쟀습니다`,
          body:
            '자동화 전에 사람이 그 일을 직접 하는 것을 재서 중앙값을 봉인했습니다. 이 횟수는 통계적으로 약합니다. 그날 컨디션이나 파일 상태에 따라 20분씩 차이가 날 수 있습니다.',
          instead:
            '그래서 이 값에 신뢰구간을 붙이지 않았습니다. "97분"이라고만 적고 "97±4분"이라고 적지 않습니다. 절감액도 이 값 위에서만 계산하고, 몇 번 잰 값인지를 화면에서 떼지 않습니다.',
        },
    {
      key: 'fake_data',
      title: '실제 회사 데이터가 아닙니다',
      body:
        '여기 나오는 회사·부서·사람·정산 금액은 전부 만든 것입니다. 실제 사내 자료를 쓸 수 없어서 직접 만들었습니다.',
      instead:
        '대신 더러움을 일부러 넣었습니다 — 병합된 셀, 머리글이 넷째 줄에서 시작하는 시트, CP949로 저장돼 한글이 깨지는 파일, 합계 줄이 섞인 표, 통화가 셋인 원장. 실제로 받는 파일이 깨끗하지 않다는 것이 이 도구의 존재 이유라서, 거기서만은 봐주지 않았습니다.',
    },
    finished === 0
      ? {
          key: 'one_case',
          title: '여덟 단계를 끝까지 간 것이 아직 한 건도 없습니다',
          body:
            '검토·협의안·제작·베타테스트·사용법서·배포·성과까지 전부 밟은 신청서가 현재 없습니다. 이 여덟 단계가 실제 병목에서 통하는지는 아직 보여드리지 못했습니다.',
          instead:
            '대신 각 단계가 무엇을 막고 무엇을 요구하는지는 직접 눌러서 확인하실 수 있습니다. 로그인이 없으므로 예시를 넣고 판정부터 성과까지 직접 밟아 보실 수 있습니다.',
        }
      : {
          key: 'one_case',
          title:
            finished === 1
              ? '여덟 단계를 끝까지 간 것은 한 건뿐입니다'
              : `여덟 단계를 끝까지 간 것은 ${finished}건입니다`,
          body:
            '나머지는 앞 단계에 서 있습니다. 여러 종류의 병목에서 이 여덟 단계가 똑같이 통하는지는 아직 증명하지 못했습니다.',
          instead:
            '한 건을 얕게 여덟 번 보여 주는 대신 끝까지 판 것을 보여드립니다. 각 단계에서 무엇을 정했고 왜 그렇게 정했고 무엇을 고르지 않았는지가 전부 남아 있습니다.',
        },
    {
      key: 'no_ai',
      title: 'AI가 판단하는 부분이 없습니다',
      body:
        '파일을 읽고 합치고 검산하는 일은 전부 정해진 규칙이 합니다. 비슷한 신청서를 찾는 것도 낱말이 겹치는지 세는 것이지 뜻을 이해하는 것이 아닙니다. 그래서 규칙에 없는 모양의 파일이 오면 처리하지 못하고 격리합니다.',
      instead:
        '대신 같은 파일을 넣으면 언제나 같은 결과가 나오고, 어느 숫자든 눌러서 원본 파일 몇 번째 줄에서 왔는지 되짚을 수 있습니다. 틀렸을 때 어디가 왜 틀렸는지 말할 수 있는 것을 골랐습니다.',
    },
    runs === 0
      ? {
          key: 'not_operated',
          title: '넘긴 도구가 실제로 돌아간 적이 없습니다',
          body:
            '부서에 넘긴 뒤 실제로 몇 번 쓰였는지를 세는 자리가 있는데, 지금 셀 것이 없습니다. 사람이 지쳐 안 쓰게 되는지, 파일 양식이 바뀌어 깨지는지는 겪어 보지 못했습니다.',
          instead:
            '그래서 안 쓰이는 도구를 숨기지 않고 그대로 0으로 세어 둡니다. 세는 자리를 먼저 만들어 두는 것이 나중에 숫자를 만들어 내는 것보다 낫다고 봤습니다.',
        }
      : {
          key: 'not_operated',
          title: '실제 부서가 몇 달 써 본 것이 아닙니다',
          body: `넘긴 뒤 실제로 쓰인 횟수는 ${runs}번이 전부입니다. 몇 달 돌려 보면서 사람이 지쳐 안 쓰게 되는지, 파일 양식이 바뀌어 깨지는지는 겪어 보지 못했습니다.`,
          instead:
            '그래서 "넘긴 뒤" 화면에 안 쓰이는 도구를 숨기지 않고 그대로 세어 둡니다. 지금은 셀 것이 적지만, 세는 자리를 먼저 만들어 뒀습니다.',
        },
  ]
}
