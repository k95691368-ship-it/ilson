// 부서 목록. 한 벌만 둔다.
//
// 같은 배열이 다섯 군데에 따로 적혀 있었다 — 신청서·협의안·베타테스트·배포
// 화면과 서버. 그리고 그중 둘(베타테스트·배포)에서 **인사가 빠져 있었다.**
//
// 그래서 이런 일이 났다. 인사 부서가 신청서를 낸다. 접수되고, 판정되고,
// 협의안까지 간다. 그런데 베타테스트 화면에서 "어느 부서가 써 볼 것인가"를
// 고르려고 열면 인사가 목록에 없다. 배포 화면에서 "어느 부서에 넘길
// 것인가"에도 없다. 서버는 인사를 받아 준다(functions/_lib/applications.js가
// 일곱 개를 갖고 있었다). 화면만 안 내놓은 것이다.
//
// 아무도 예외를 안 던진다. 화면도 안 깨진다. 그냥 그 부서가 목록에 없을
// 뿐이고, 고르려던 사람은 자기가 뭘 잘못 눌렀나 한다.
//
// 이 저장소는 "검증은 한 벌만 둔다"를 원칙으로 적어 두고 있다. 목록도
// 검증이다 — 무엇이 유효한 부서인가를 정하는 것이기 때문이다.
export const DEPTS = ['재무', '마케팅', '영업', 'SCM', '운영', '인사', '기타']

// 아는 부서인가.
export function isDept(name) {
  return DEPTS.includes(String(name ?? '').trim())
}
